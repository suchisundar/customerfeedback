#!/usr/bin/env node
/* Embeds the sample CSVs in data/sample-data.js so index.html works when opened
 * straight from disk (browsers block fetch() on file:// URLs).
 * Run after editing anything in data/*.csv:  npm run build:data */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'data');
const samples = {
  dataset: {
    label: 'Full dataset (19 fields)',
    file: 'flowpilot_feedback_dataset.csv',
  },
  comments: {
    label: 'Comments only (text)',
    file: 'flowpilot_feedback_comments.csv',
  },
};
for (const s of Object.values(samples)) s.csv = fs.readFileSync(path.join(dir, s.file), 'utf8');

const out = '/* Generated by scripts/build-sample-data.js. Do not edit by hand. */\n' +
  'window.FLOWPILOT_SAMPLES = ' + JSON.stringify(samples, null, 2) + ';\n';
fs.writeFileSync(path.join(dir, 'sample-data.js'), out);
console.log('Wrote data/sample-data.js');
